  await expect(page.getByText(/This task is archived/)).toBeVisible();
  await first.click(); await expect(first).not.toBeChecked();
  await page.reload(); await expect(first).not.toBeChecked();
  await expect(page.getByText('0 of 2 steps completed',{exact:true})).toBeVisible();
  await second.click(); await expect(second).toBeChecked();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  const logout=await page.context().newPage();await logout.goto('/dashboard');
