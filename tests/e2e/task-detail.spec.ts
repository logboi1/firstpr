  test.setTimeout(60000);
  await request.get('http://127.0.0.1:54329/reset');
  await request.get('http://127.0.0.1:54329/directory-control?mode=normal');
  const {task}=await(await request.get('http://127.0.0.1:54329/task-control')).json();
  await page.goto(`/opportunities/${task}`);
  await expect(page.getByRole('heading',{name:'[DEMO] Documentation task 1',exact:true})).toBeVisible();
  await expect(page.getByText('Read the fictional contribution guide',{exact:true})).toBeVisible();
  await expect(page.getByText('Install dependencies\nRun the tests',{exact:true})).toBeVisible();
  await expect(page.getByRole('link',{name:'Open repository ↗',exact:true})).toHaveAttribute('rel','noopener noreferrer');
  await expect(page.getByRole('checkbox')).toHaveCount(0);
  await expect(page.getByRole('link',{name:'Sign in to save progress',exact:true})).toBeVisible();
  await page.goto('/opportunities/not-a-uuid');
  await expect(page.getByRole('heading',{name:'Task unavailable',exact:true})).toBeVisible();
  await signIn(page,'ada@example.com','Ada');
  await page.goto(`/opportunities/${task}`);
  await page.getByRole('button',{name:'Start this task',exact:true}).click();
  const first=page.getByRole('checkbox',{name:'Read the contribution guide',exact:true});
  const second=page.getByRole('checkbox',{name:'Run the project tests',exact:true});
  await expect(first).not.toBeChecked();
  await first.focus(); await page.keyboard.press('Space');
  await expect(first).toBeChecked();
  await expect(page.getByText('1 of 2 steps completed',{exact:true})).toBeVisible();
  await page.reload(); await expect(first).toBeChecked();
  const bobContext=await browser.newContext();
  const bob=await bobContext.newPage();
  await signIn(bob,'bob@example.com','Bob');
  await bob.goto(`/opportunities/${task}`);
  await bob.getByRole('button',{name:'Start this task',exact:true}).click();
  const bobFirst=bob.getByRole('checkbox',{name:'Read the contribution guide',exact:true});
  const bobSecond=bob.getByRole('checkbox',{name:'Run the project tests',exact:true});
  await expect(bobFirst).not.toBeChecked();
  await bobSecond.click(); await expect(bobSecond).toBeChecked();
  await page.reload(); await expect(first).toBeChecked(); await expect(second).not.toBeChecked();
  await request.get('http://127.0.0.1:54329/task-control?archive=true');
  const visitor=await browser.newContext();const anonymous=await visitor.newPage();
  await anonymous.goto(`/opportunities/${task}`);
  await expect(anonymous.getByRole('heading',{name:'Task unavailable',exact:true})).toBeVisible();
