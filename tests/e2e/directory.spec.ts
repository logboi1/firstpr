import { test, expect } from '@playwright/test';
test.beforeEach(async ({ request }) => { await request.get('http://127.0.0.1:54329/directory-control?mode=normal'); });
test('public cards, combined filters, pagination, URL persistence, keyboard controls and no-match recovery', async ({ page }) => {
  await page.goto('/opportunities');
  await expect(page.getByRole('status')).toContainText('14 opportunities available');
  await expect(page.locator('.opportunity-card')).toHaveCount(12);
  await expect(page.getByText('[DEMO] Secret draft', {exact:true})).toHaveCount(0);
  await expect(page.getByText('[DEMO] Archived task', {exact:true})).toHaveCount(0);
  await expect(page.getByLabel('Skill', {exact:true}).locator('option').filter({hasText:/DraftOnly|ArchivedOnly/})).toHaveCount(0);
  await page.getByRole('link', {name:'Next page',exact:true}).click();
  await expect(page).toHaveURL(/page=2/);
  await expect(page.locator('.opportunity-card')).toHaveCount(2);
  await page.getByLabel('Search tasks', {exact:true}).fill('setup');
  await page.getByLabel('Skill', {exact:true}).selectOption('Markdown');
  await page.getByLabel('Contribution type', {exact:true}).selectOption('documentation');
  await page.getByLabel('Difficulty', {exact:true}).selectOption('beginner');
  await page.getByRole('button', {name:'Apply filters',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('13 opportunities matching your filters');
  await expect(page.locator('.opportunity-card')).toHaveCount(12);
  expect(new URL(page.url()).searchParams.has('page')).toBe(false);
  await page.getByRole('link', {name:'Next page',exact:true}).click();
  await expect(page.locator('.opportunity-card')).toHaveCount(1);
  const params = new URL(page.url()).searchParams;
  expect(params.get('skill')).toBe('Markdown'); expect(params.get('q')).toBe('setup');
  await page.reload();
  await expect(page.getByLabel('Search tasks', {exact:true})).toHaveValue('setup');
  await page.getByLabel('Search tasks', {exact:true}).fill('keyboard');
  await page.getByLabel('Skill', {exact:true}).selectOption('React');
  await page.getByLabel('Contribution type', {exact:true}).selectOption('testing');
  await page.getByLabel('Difficulty', {exact:true}).selectOption('intermediate');
  await page.getByLabel('Search tasks', {exact:true}).focus();
  await page.keyboard.press('Tab'); await expect(page.getByLabel('Skill', {exact:true})).toBeFocused();
  await page.keyboard.press('Tab'); await expect(page.getByLabel('Contribution type', {exact:true})).toBeFocused();
  await page.keyboard.press('Tab'); await expect(page.getByLabel('Difficulty', {exact:true})).toBeFocused();
  await page.keyboard.press('Tab'); await expect(page.getByRole('button', {name:'Apply filters',exact:true})).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('status')).toContainText('1 opportunity matching your filters');
  await expect(page.locator('.opportunity-card')).toHaveCount(1);
  const source = page.getByRole('link', {name:'View source issue for [DEMO] React keyboard testing (opens in a new tab)',exact:true});
  await expect(source).toHaveAttribute('href','https://example.invalid/ui/issues/1');
  await expect(source).toHaveAttribute('rel','noopener noreferrer');
  await page.getByLabel('Search tasks', {exact:true}).fill('no matching task');
  await page.getByRole('button', {name:'Apply filters',exact:true}).click();
  await expect(page.getByRole('heading', {name:'No tasks match these filters.',exact:true})).toBeVisible();
  await page.goBack();
  await expect(page.getByLabel('Search tasks', {exact:true})).toHaveValue('keyboard');
  await page.getByRole('link', {name:'Clear filters',exact:true}).click();
  await expect(page).toHaveURL(/\/opportunities$/);
  await expect(page.getByLabel('Search tasks', {exact:true})).toHaveValue('');
});
test('empty directory, provider error recovery and loading feedback', async ({ page, request }) => {
  await request.get('http://127.0.0.1:54329/directory-control?mode=empty');
  await page.goto('/opportunities');
  await expect(page.getByRole('heading', {name:'New opportunities are on the way.',exact:true})).toBeVisible();
  await request.get('http://127.0.0.1:54329/directory-control?mode=error-once');
  await page.goto('/opportunities?q=keyboard');
  await expect(page.getByRole('heading', {name:'We could not load the opportunities.',exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Try again',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('1 opportunity matching your filters');
  await expect(page.getByLabel('Search tasks', {exact:true})).toHaveValue('keyboard');
  await request.get('http://127.0.0.1:54329/directory-control?mode=error-once');
  await page.goto('/opportunities?q=setup');
  await expect(page.getByRole('heading', {name:'We could not load the opportunities.',exact:true})).toBeVisible();
  await page.getByRole('link', {name:'Clear filters and retry',exact:true}).click();
  await expect(page).toHaveURL(/\/opportunities$/);
  await expect(page.getByRole('status')).toContainText('14 opportunities available');
  await request.get('http://127.0.0.1:54329/directory-control?mode=slow');
  await page.goto('/opportunities?q=documentation', {waitUntil:'commit'});
  await expect(page.getByRole('status').filter({hasText:'Loading opportunities'})).toBeVisible();
  await expect(page.getByRole('status')).toContainText('13 opportunities matching your filters');
});
test('mobile directory has a single column and no horizontal overflow', async ({ page }) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('/opportunities?q=keyboard');
  await expect(page.locator('.opportunity-card')).toHaveCount(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await expect(page.getByLabel('Search tasks', {exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Apply filters',exact:true}).click();
  await expect(page.locator('.opportunity-card')).toHaveCount(1);
});
